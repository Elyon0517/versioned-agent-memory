"""Run real memory operations and export a self-contained, inspectable report.

From the repository root: python examples/showcase.py
"""

from __future__ import annotations

import json
from dataclasses import asdict
from html import escape
from pathlib import Path

from agent_memory_kit import MemoryEngine, Message, Observation, Scope, SessionMemory
from agent_memory_kit.adapters import InMemoryStore


def run_demo() -> dict:
    engine = MemoryEngine(InMemoryStore())
    alice, bob = Scope("demo", "alice"), Scope("demo", "bob")
    steps = []

    def record(title: str, result: object) -> None:
        steps.append({"title": title, "result": asdict(result)})

    original = Observation("event-1", "home-city", 1, "Home city: Seattle", ("profile:1",))
    created = engine.observe(alice, original)
    record("Observe a sourced fact", created)
    replay = engine.observe(alice, original)
    assert replay.replayed and replay.memory.version == 1
    record("Replay the same event safely", replay)
    corrected = engine.correct(
        alice,
        created.memory.id,
        "Home city: Boston",
        evidence=("user:correction-1",),
        expected_version=1,
        operation_id="correct-1",
    )
    record("User corrects Seattle to Boston", corrected)
    protected = engine.observe(
        alice, Observation("event-2", "home-city", 2, "Home city: Seattle", ("profile:2",))
    )
    assert protected.outcome == "protected_by_user" and "Boston" in protected.memory.content
    record("A later source cannot overwrite the correction", protected)
    isolated = engine.active(bob)
    assert isolated == ()
    sessions = SessionMemory()
    sessions.append(alice, "trip", Message("m1", "user", "Plan a weekend in Boston"), ttl=3600)
    assert sessions.load(bob, "trip").messages == ()
    forgotten = engine.forget(
        alice, created.memory.id, expected_version=2, operation_id="forget-1"
    )
    record("Forget: revoke the canonical memory", forgotten)
    assert engine.active(alice) == ()
    blocked = engine.observe(
        alice, Observation("event-3", "home-city", 3, "Home city: Seattle", ("profile:3",))
    )
    assert blocked.outcome == "blocked_by_forget"
    record("New observations cannot resurrect it", blocked)
    return {
        "steps": steps,
        "other_user_memories": len(isolated),
        "other_user_messages": len(sessions.load(bob, "trip").messages),
        "active_after_forget": len(engine.active(alice)),
    }


def main() -> None:
    data = run_demo()
    out = Path("docs/showcase")
    out.mkdir(parents=True, exist_ok=True)
    (out / "memory.json").write_text(json.dumps(data, indent=2) + "\n")
    cards = ""
    for number, step in enumerate(data["steps"], 1):
        result = step["result"]
        memory = result["memory"]
        content = escape(memory["content"] or "[revoked — no active content]")
        cards += (
            f'<article class="card"><small>STEP {number:02d} · '
            f"MEMORY v{memory['version']}</small>"
            f"<h3>{escape(step['title'])}</h3><p>{content}</p>"
            f'<span class="tag">{escape(result["outcome"])}'
            f"{' · replayed' if result['replayed'] else ''}</span>"
            "<details><summary>Inspect SDK receipt &amp; evidence</summary>"
            f"<pre>{escape(json.dumps(result, indent=2))}</pre></details></article>"
        )
    css = Path(__file__).with_name("showcase.css").read_text()
    document = f"""<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Versioned Agent Memory — executable walkthrough</title><style>{css}</style>
<main><header><div class="eyebrow">VERSIONED AGENT MEMORY / SDK WALKTHROUGH</div>
<h1>Remember. Correct. Respect.</h1><p>One fact through its lifecycle — real SDK calls,
versioned receipts, and explicit user control.</p></header>
<div class="stats"><div class="stat"><strong>{len(data["steps"])}</strong>
verified lifecycle steps</div>
<div class="stat"><strong>{data["other_user_memories"]}</strong>
memories visible to another user</div>
<div class="stat"><strong>{data["active_after_forget"]}</strong>
active memories after forgetting</div></div>
<div class="flow" aria-label="Memory lifecycle"><span>Observe<br>Seattle · v1</span>→
<span>Correct<br>Boston · v2</span>→<span>Protect<br>User override</span>→
<span>Forget<br>Revoked · v3</span></div><div class="grid">{cards}</div>
<footer>Generated by <code>python examples/showcase.py</code> ·
Synthetic data, real in-memory SDK.
Session isolation is also asserted. Forgetting is logical revocation, not backup erasure.
<a href="memory.json">Download receipts as JSON</a></footer></main></html>"""
    (out / "index.html").write_text(document)
    print(f"Verified {len(data['steps'])} steps; open {out / 'index.html'}")


if __name__ == "__main__":
    main()
